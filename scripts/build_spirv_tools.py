"""Build SPIRV-Tools from source and package it as the binary target
Package.swift takes: Dependencies/CSpirvTools.xcframework.

    uv run scripts/build_spirv_tools.py

SPIRV-Tools and SPIRV-Headers are cloned at the same Vulkan SDK tag into
scripts/.work, so repeated runs are incremental (--clean starts fresh). The
libraries are static — SPIRV-Tools itself plus its opt, diff, reduce, link
and lint libraries — merged into one archive, libCSpirvTools.a, and shipped
with the C API (spirv-tools/libspirv.h) and a module map for module
`CSpirvTools`. The executables are not built: everything goes through the
library.

macOS only for now: one slice, arm64 + x86_64 in one CMake build. Homebrew
no longer builds Intel bottles, which is why this is built here at all
rather than taken from a package manager.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

# --- Paths -----------------------------------------------------------------

SCRIPT_DIR = Path(__file__).resolve().parent
PACKAGE_ROOT = SCRIPT_DIR.parent
DEPENDENCIES_DIR = PACKAGE_ROOT / "Dependencies"
DEFAULT_WORK_DIR = SCRIPT_DIR / ".work"

# --- Upstream sources ------------------------------------------------------

SPIRV_TOOLS_REPO = "https://github.com/KhronosGroup/SPIRV-Tools.git"
SPIRV_HEADERS_REPO = "https://github.com/KhronosGroup/SPIRV-Headers.git"
# One tag for both: each Vulkan SDK release tags a matching pair.
SDK_REF = "vulkan-sdk-1.4.363.0"

# The static libraries merged into libCSpirvTools.a: CMake target -> archive.
LIBRARIES = {
    "SPIRV-Tools-static": "libSPIRV-Tools.a",
    "SPIRV-Tools-opt": "libSPIRV-Tools-opt.a",
    "SPIRV-Tools-diff": "libSPIRV-Tools-diff.a",
    "SPIRV-Tools-reduce": "libSPIRV-Tools-reduce.a",
    "SPIRV-Tools-link": "libSPIRV-Tools-link.a",
    "SPIRV-Tools-lint": "libSPIRV-Tools-lint.a",
}

ARCHITECTURES = "arm64;x86_64"
DEPLOYMENT_TARGET = "14.0"

MODULEMAP = """module CSpirvTools {
    header "spirv-tools/libspirv.h"
    link "c++"
    export *
}
"""


def log(message: str) -> None:
    print(f"[build_spirv_tools] {message}", flush=True)


def run(cmd: list[str], cwd: Path | None = None) -> None:
    log("$ " + " ".join(cmd))
    subprocess.run(cmd, cwd=cwd, check=True)


def require(tool: str) -> str:
    path = shutil.which(tool)
    if path is None:
        sys.exit(f"error: {tool} not found on PATH")
    return path


def sync_repo(repo: str, ref: str, dest: Path) -> None:
    if (dest / ".git").is_dir():
        run(["git", "fetch", "--tags", "--depth", "1", "origin", ref], cwd=dest)
        run(["git", "checkout", "--force", ref], cwd=dest)
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        run(["git", "clone", "--depth", "1", "--branch", ref, repo, str(dest)])


def build(work_dir: Path, jobs: int) -> Path:
    """Configure and build the static libraries; returns the build directory."""
    cmake = require("cmake")
    ninja = require("ninja")
    tools = work_dir / "SPIRV-Tools"
    headers = work_dir / "SPIRV-Headers"
    sync_repo(SPIRV_TOOLS_REPO, SDK_REF, tools)
    sync_repo(SPIRV_HEADERS_REPO, SDK_REF, headers)

    build_dir = work_dir / "build" / "spirv-tools-macos"
    run([
        cmake, "-S", str(tools), "-B", str(build_dir), "-G", "Ninja",
        f"-DCMAKE_MAKE_PROGRAM={ninja}",
        "-DCMAKE_BUILD_TYPE=Release",
        "-DCMAKE_OSX_SYSROOT=macosx",
        f"-DCMAKE_OSX_ARCHITECTURES={ARCHITECTURES}",
        f"-DCMAKE_OSX_DEPLOYMENT_TARGET={DEPLOYMENT_TARGET}",
        f"-DSPIRV-Headers_SOURCE_DIR={headers}",
        # The grammar tables are generated by Python scripts at build time.
        f"-DPython3_EXECUTABLE={sys.executable}",
        "-DBUILD_SHARED_LIBS=OFF",
        "-DSPIRV_SKIP_TESTS=ON",
        "-DSPIRV_SKIP_EXECUTABLES=ON",
        "-DSPIRV_WERROR=OFF",
        "-DSPIRV_TOOLS_BUILD_STATIC=ON",
    ])
    run([cmake, "--build", str(build_dir), "--parallel", str(jobs), "--target", *LIBRARIES])
    return build_dir


def package(work_dir: Path, build_dir: Path) -> Path:
    """Merge the archives and wrap them, with the C API, in the xcframework."""
    stage = work_dir / "stage-macos"
    if stage.exists():
        shutil.rmtree(stage)
    include = stage / "include"
    (include / "spirv-tools").mkdir(parents=True)
    shutil.copy2(work_dir / "SPIRV-Tools" / "include" / "spirv-tools" / "libspirv.h",
                 include / "spirv-tools" / "libspirv.h")
    (include / "module.modulemap").write_text(MODULEMAP)

    archives = []
    for archive in LIBRARIES.values():
        found = sorted(build_dir.rglob(archive))
        if len(found) != 1:
            sys.exit(f"error: expected one {archive} under {build_dir}, found {len(found)}")
        archives.append(str(found[0]))
    merged = stage / "libCSpirvTools.a"
    run(["libtool", "-static", "-no_warning_for_no_symbols", "-o", str(merged), *archives])

    out = DEPENDENCIES_DIR / "CSpirvTools.xcframework"
    if out.exists():
        shutil.rmtree(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    run(["xcodebuild", "-create-xcframework", "-library", str(merged), "-headers", str(include),
         "-output", str(out)])
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--work-dir", type=Path, default=DEFAULT_WORK_DIR)
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    parser.add_argument("--clean", action="store_true", help="delete the work directory first")
    args = parser.parse_args()

    if sys.platform != "darwin":
        sys.exit("error: only macOS is built so far")
    for tool in ("git", "libtool", "xcodebuild"):
        require(tool)

    work_dir: Path = args.work_dir.resolve()
    if args.clean and work_dir.exists():
        shutil.rmtree(work_dir)
    build_dir = build(work_dir, args.jobs)
    out = package(work_dir, build_dir)
    log(f"installed -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
